#!/usr/bin/env bash
# Office Unbound ICS - prepare the PRIMARY controller for a warm standby (ADR-0012). Run as root on the primary, once per standby.
#   sudo ics-standby-prepare-primary.sh --primary-ip 192.0.2.10 --standby-ip 192.0.2.11 [--out-dir /root/ics-standby]
# Does (idempotent):
#   * PostgreSQL: TLS on (the ICS server certificate), listen on loopback + --primary-ip, wal_level=replica, a bounded physical slot
#   * dedicated role `replicator` (REPLICATION LOGIN only, scram) and a hostssl-only pg_hba line for the standby address
#   * nftables: port 5432 reachable only from loopback, the primary itself and the standby
#   * an ENCRYPTED key bundle (vault/audit/signing keys, env files, replicator password, CA) + a separate passphrase file.
#     This is the explicit, audited key transfer: the bundle and the passphrase must travel by different channels.
# Physical (not logical) replication: the whole cluster incl. the hash-chained audit log, sequences and DDL is copied byte for byte,
# so the standby is an exact point-in-time copy and the audit chain continues unbroken after promotion.
set -euo pipefail
ETC=/etc/office-unbound; OPT=/opt/office-unbound/ics; TLS=$ETC/tls
PGC=$(ls -d /etc/postgresql/*/main 2>/dev/null | sort -V | tail -1); [ -n "$PGC" ] || { echo "no PostgreSQL cluster config under /etc/postgresql" >&2; exit 1; }
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PRIMARY_IP=""; STANDBY_IP=""; OUT=/root/ics-standby
die() { echo "standby-prepare: ERROR: $*" >&2; exit 1; }
log() { echo "standby-prepare: $*"; }
while [ $# -gt 0 ]; do
  case "$1" in
    --primary-ip) PRIMARY_IP="${2:?}"; shift 2;;
    --standby-ip) STANDBY_IP="${2:?}"; shift 2;;
    --out-dir) OUT="${2:?}"; shift 2;;
    *) die "unknown argument $1";;
  esac
done
[ "$(id -u)" = 0 ] || die "run as root"
[ -n "$PRIMARY_IP" ] && [ -n "$STANDBY_IP" ] || die "--primary-ip and --standby-ip are required"
for ip in "$PRIMARY_IP" "$STANDBY_IP"; do python3 -I -c 'import ipaddress,sys; a=ipaddress.ip_address(sys.argv[1]); assert a.version==4 and not a.is_unspecified' "$ip" 2>/dev/null || die "invalid IPv4 address: $ip"; done
ip -4 -o addr show | awk '{print $4}' | cut -d/ -f1 | grep -qx "$PRIMARY_IP" || die "--primary-ip $PRIMARY_IP is not configured on this host"
[ -f "$TLS/ics.crt" ] && [ -f "$TLS/ics.key" ] && [ -f "$TLS/ca.crt" ] || die "needs a TLS installation (bootstrap.sh without --skip-tls): the replication stream is verified against $TLS/ca.crt"
openssl x509 -in "$TLS/ics.crt" -noout -checkip "$PRIMARY_IP" | grep -q 'does match' || die "the server certificate does not cover $PRIMARY_IP (the standby verifies it)"
[ -x "$OPT/.venv/bin/python" ] || die "ICS is not installed here"
psqlpg() { runuser -u postgres -- psql -X -q -v ON_ERROR_STOP=1 "$@"; }
changed=0

# --- PostgreSQL server certificate (the ICS certificate; the standby verifies it with ca.crt, sslmode=verify-full)
install -m 0644 -o postgres -g postgres "$TLS/ics.crt" "$PGC/ou-pg.crt.new"; install -m 0600 -o postgres -g postgres "$TLS/ics.key" "$PGC/ou-pg.key.new"
for f in ou-pg.crt ou-pg.key; do
  if [ -f "$PGC/$f" ] && cmp -s "$PGC/$f.new" "$PGC/$f"; then rm -f "$PGC/$f.new"; else mv "$PGC/$f.new" "$PGC/$f"; changed=1; fi
done

# --- server settings (drop-in; the main postgresql.conf is untouched)
cat > "$PGC/conf.d/.90-ou-replication.new" <<EOF
# Office Unbound warm standby (ADR-0012). Generated by ics-standby-prepare-primary.sh.
listen_addresses = '127.0.0.1,$PRIMARY_IP'
ssl = on
ssl_cert_file = '$PGC/ou-pg.crt'
ssl_key_file = '$PGC/ou-pg.key'
ssl_min_protocol_version = 'TLSv1.2'
password_encryption = scram-sha-256
wal_level = replica
max_wal_senders = 4
max_replication_slots = 4
max_slot_wal_keep_size = 2GB
EOF
if [ -f "$PGC/conf.d/90-ou-replication.conf" ] && cmp -s "$PGC/conf.d/.90-ou-replication.new" "$PGC/conf.d/90-ou-replication.conf"; then rm -f "$PGC/conf.d/.90-ou-replication.new"
else mv "$PGC/conf.d/.90-ou-replication.new" "$PGC/conf.d/90-ou-replication.conf"; chmod 0644 "$PGC/conf.d/90-ou-replication.conf"; changed=1; fi

# --- replicator role
install -d -m 0711 "$ETC"
if [ ! -s "$ETC/replicator.pw" ]; then ( umask 077; python3 -I -c 'import secrets; print(secrets.token_urlsafe(32))' > "$ETC/replicator.pw" ); log "generated $ETC/replicator.pw"; fi
chmod 0600 "$ETC/replicator.pw"; chown root:root "$ETC/replicator.pw"
RPW="$(cat "$ETC/replicator.pw")"
if [ "$(runuser -u postgres -- psql -X -Atc "select 1 from pg_roles where rolname='replicator'")" = 1 ]; then
  printf "ALTER ROLE replicator REPLICATION LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '%s';\n" "$RPW" | psqlpg
else
  printf "CREATE ROLE replicator REPLICATION LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '%s';\n" "$RPW" | psqlpg; log "created role replicator"
fi
unset RPW

# --- pg_hba: hostssl only, only the standby address, only the replication pseudo-database
HBA=$PGC/pg_hba.conf
grep -v '# ou-standby$' "$HBA" > "$HBA.new" || true
echo "hostssl replication replicator $STANDBY_IP/32 scram-sha-256 # ou-standby" >> "$HBA.new"
if ! cmp -s "$HBA.new" "$HBA"; then cat "$HBA.new" > "$HBA"; changed=1; fi
rm -f "$HBA.new"

# --- firewall for 5432
cat > "$ETC/ics-pg-fw.nft" <<EOF
# Office Unbound: PostgreSQL (5432) only from this host and the standby. Generated by ics-standby-prepare-primary.sh.
table inet ics_pg {
  chain input {
    type filter hook input priority -10; policy accept;
    tcp dport 5432 ip saddr { 127.0.0.1, $PRIMARY_IP, $STANDBY_IP } accept
    tcp dport 5432 drop
  }
}
EOF
cat > /etc/systemd/system/ics-pg-fw.service <<'EOF'
[Unit]
Description=Office Unbound PostgreSQL source restriction
After=network-pre.target
Before=postgresql.service
[Service]
Type=oneshot
RemainAfterExit=yes
ExecStartPre=-/usr/sbin/nft delete table inet ics_pg
ExecStart=/usr/sbin/nft -f /etc/office-unbound/ics-pg-fw.nft
ExecStop=/usr/sbin/nft delete table inet ics_pg
[Install]
WantedBy=multi-user.target
EOF
nft -c -f "$ETC/ics-pg-fw.nft" || die "generated nft ruleset invalid"
systemctl daemon-reload; systemctl enable ics-pg-fw.service >/dev/null 2>&1; systemctl restart ics-pg-fw.service

# --- restart only when the listening/TLS/wal settings changed (the console reconnects by itself: pool_pre_ping)
if [ "$changed" = 1 ]; then log "PostgreSQL settings changed: restarting postgresql (brief interruption)"; systemctl restart postgresql.service
else systemctl reload postgresql.service; fi
for _ in $(seq 1 60); do pg_isready -q -h "$PRIMARY_IP" && break; sleep 1; done
pg_isready -q -h "$PRIMARY_IP" || die "PostgreSQL does not answer on $PRIMARY_IP"

# --- physical slot (bounded by max_slot_wal_keep_size, so a dead standby cannot fill this disk)
psqlpg -c "SELECT pg_create_physical_replication_slot('ics_standby') WHERE NOT EXISTS (SELECT 1 FROM pg_replication_slots WHERE slot_name='ics_standby')" >/dev/null

# --- encrypted key bundle + audit
install -d -m 0700 "$OUT"
"$OPT/.venv/bin/python" -I "$SRC/ics/keybundle.py" export --out "$OUT/ics-standby-keys.bundle" --passphrase-out "$OUT/ics-standby-keys.passphrase" \
  --replicator-password-file "$ETC/replicator.pw" --primary-ip "$PRIMARY_IP" --primary-ca "$TLS/ca.crt"
(cd "$OPT" && runuser -u ics -- "$OPT/.venv/bin/python" -m ics.cli standby-note keys-exported --standby-ip "$STANDBY_IP")
echo
echo "================ standby preparation done ================"
echo "bundle      : $OUT/ics-standby-keys.bundle   (AES-256-GCM, scrypt)"
echo "passphrase  : $OUT/ics-standby-keys.passphrase   -> hand over by a DIFFERENT channel, then delete both files on this host"
echo "bundle sha256: $(sha256sum "$OUT/ics-standby-keys.bundle" | cut -d' ' -f1)"
echo "On the standby (fresh Ubuntu 24.04, ICS source tree):"
echo "  sudo ics/deploy/bootstrap.sh --standby-of $PRIMARY_IP --key-bundle ics-standby-keys.bundle --bundle-passphrase-file ics-standby-keys.passphrase \\"
echo "       --listen-ip <standby ip> --allow-cidr <admin cidr>"
echo "Replication status here:  sudo -u postgres psql -c 'select client_addr,state,sent_lsn,replay_lsn,replay_lag from pg_stat_replication'"
