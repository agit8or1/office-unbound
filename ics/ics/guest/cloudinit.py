"""cloud-init user-data renderer for Office Unbound guests (ADR-0009 section 5). `render(spec) -> str` is a pure, deterministic function:
same spec -> same bytes. The output contains NO secret: the enrollment token is generated by the ICS and only its SHA-256 is given to the
guest (the agent stores only the hash anyway), so nothing sensitive reaches user-data, the hypervisor snippet store, /var/lib/cloud or any log.
Every value interpolated into the bootstrap script has passed a closed-shape validator and is shlex-quoted as well."""
import base64
import gzip
import hashlib
import io
import json
import ipaddress
import os
import re
import shlex
import tarfile
from typing import Literal

import yaml
from cryptography.hazmat.primitives import serialization
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

SERVICE_USER = "ou-svc"
SERVICE_HOME = "/var/lib/ou-svc"
BREAK_GLASS_USER = "ou-admin"
LABEL_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")
DOMAIN_RE = re.compile(r"^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$|^[a-z0-9-]+(\.[a-z0-9-]+)*\.(internal|lab|local|test)$")
PKG_RE = re.compile(r"^[a-z0-9][a-z0-9+.-]{1,62}$")
REGISTRY_RE = re.compile(r"^[a-z0-9]([a-z0-9.-]{0,120}[a-z0-9])?(:[0-9]{1,5})?$")
TZ_RE = re.compile(r"^[A-Za-z]+(/[A-Za-z0-9_+-]+){0,2}$")
SSH_KEY_RE = re.compile(r"^(ssh-ed25519|sk-ssh-ed25519@openssh\.com|ecdsa-sha2-nistp(256|384|521)|ssh-rsa) [A-Za-z0-9+/=]{40,800}( [A-Za-z0-9@._-]{0,64})?$")
HEX40, HEX64 = re.compile(r"^[0-9A-F]{40}$"), re.compile(r"^[0-9a-f]{64}$")
SUITES = {"ubuntu-24.04": ("ubuntu", "noble"), "debian-12": ("debian", "bookworm")}
BASE_PACKAGES = ["podman", "uidmap", "slirp4netns", "passt", "crun", "netavark", "aardvark-dns", "systemd-container", "systemd-timesyncd", "dbus-user-session",
                 "nftables", "polkitd", "python3-cryptography", "gnupg", "ca-certificates", "unattended-upgrades", "apt-utils"]
KEYRING = {"ubuntu": "/usr/share/keyrings/ubuntu-archive-keyring.gpg", "debian": "/usr/share/keyrings/debian-archive-keyring.gpg"}


class OuRepo(BaseModel):
    """The Office Unbound signed apt repository (ADR-0008). Used ONLY by the agent's pkg.install_pinned runbook, from its own sources.list
    and keyring directory; the key is pinned by fingerprint, which the node re-checks before every install."""
    model_config = ConfigDict(extra="forbid")
    url: str = Field(pattern=r"^(https://|file:///)[A-Za-z0-9._~/:-]{4,200}$")
    suite: str = Field(pattern=r"^[a-z0-9-]{2,30}$")
    components: list[str] = ["main"]
    key_armored: str = Field(max_length=20000)
    key_fingerprint: str                       # 40 hex, upper case: the pin

    @field_validator("key_fingerprint")
    @classmethod
    def _fpr(cls, v):
        if not HEX40.match(v):
            raise ValueError("key_fingerprint must be 40 upper-case hex characters")
        return v

    @field_validator("key_armored")
    @classmethod
    def _armor(cls, v):
        if not v.startswith("-----BEGIN PGP PUBLIC KEY BLOCK-----") or v.count("-----BEGIN") != 1:
            raise ValueError("key must be one armored OpenPGP public key block")
        return v


OU_REPO_PLACEHOLDER = {"url": "https://apt.office-unbound.invalid/ubuntu", "suite": "noble", "components": ["main"],
                       "key_fingerprint": "0" * 40}   # placeholder until the release pipeline (ADR-0008) publishes the repo and key


class Port(BaseModel):
    model_config = ConfigDict(extra="forbid")
    port: int = Field(ge=1, le=65535)
    proto: Literal["tcp", "udp"] = "tcp"
    sources: list[str] = []                    # CIDRs; empty = any source

    @field_validator("sources")
    @classmethod
    def _src(cls, v):
        return [str(ipaddress.ip_network(x, strict=False)) for x in v]


class GuestSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")
    hostname: str
    domain: str | None = None
    os: Literal["ubuntu-24.04", "debian-12"] = "ubuntu-24.04"
    timezone: str = "UTC"
    ntp_servers: list[str] = []
    break_glass_ssh_key: str | None = None     # None => SSH is disabled and masked
    unattended: Literal["security", "none"] = "security"
    extra_packages: list[str] = []
    ou_repo: OuRepo | None = None
    agent_address: str | None = None           # None => first global IPv4 at boot
    agent_port: int = Field(8443, ge=1024, le=65535)
    mgmt_sources: list[str] = Field(min_length=1)   # who may reach the agent (the ICS); required, nothing is open to the world
    declared_ports: list[Port] = []            # the ONLY other inbound ports
    image_registries: list[str] = []
    image_signing_pubkey_pem: str | None = None
    image_signing_key_sha256: str | None = None  # pin: sha256 of the DER SubjectPublicKeyInfo, checked here at render time
    pkg_allowlist: list[str] = []
    enroll_token_sha256: str
    enroll_ttl_seconds: int = Field(86400, ge=300, le=7 * 86400)
    subid_start: int = Field(100000, ge=1000, le=4_000_000_000)
    subid_count: int = Field(65536, ge=1000, le=1_000_000)
    agent_bundle_b64: str = Field(max_length=400000)   # base64 of build_agent_bundle()
    agent_bundle_sha256: str

    @field_validator("hostname")
    @classmethod
    def _h(cls, v):
        if not LABEL_RE.match(v):
            raise ValueError("hostname must be a lowercase RFC 1123 label")
        return v

    @field_validator("domain")
    @classmethod
    def _d(cls, v):
        if v is not None and not DOMAIN_RE.match(v):
            raise ValueError("invalid domain")
        return v

    @field_validator("timezone")
    @classmethod
    def _tz(cls, v):
        if not TZ_RE.match(v):
            raise ValueError("invalid timezone")
        return v

    @field_validator("ntp_servers")
    @classmethod
    def _ntp(cls, v):
        if not all(isinstance(x, str) and re.match(r"^[a-z0-9]([a-z0-9.-]{0,120}[a-z0-9])?$", x) for x in v) or len(v) > 6:
            raise ValueError("invalid ntp server")
        return v

    @field_validator("break_glass_ssh_key")
    @classmethod
    def _k(cls, v):
        if v is not None and not SSH_KEY_RE.match(v):
            raise ValueError("break_glass_ssh_key must be a single public key line (no options, no newlines)")
        return v

    @field_validator("extra_packages", "pkg_allowlist")
    @classmethod
    def _p(cls, v):
        if len(v) > 64 or not all(PKG_RE.match(x) for x in v):
            raise ValueError("invalid package name")
        return v

    @field_validator("image_registries")
    @classmethod
    def _r(cls, v):
        if len(v) > 8 or not all(REGISTRY_RE.match(x) for x in v):
            raise ValueError("invalid registry")
        return v

    @field_validator("mgmt_sources")
    @classmethod
    def _m(cls, v):
        return [str(ipaddress.ip_network(x, strict=False)) for x in v]

    @field_validator("agent_address")
    @classmethod
    def _a(cls, v):
        if v is not None:
            ipaddress.IPv4Address(v)
        return v

    @field_validator("enroll_token_sha256", "agent_bundle_sha256")
    @classmethod
    def _hex(cls, v):
        if not HEX64.match(v):
            raise ValueError("expected 64 lowercase hex characters")
        return v

    @model_validator(mode="after")
    def _cross(self):
        if bool(self.image_registries) != bool(self.image_signing_pubkey_pem):
            raise ValueError("image_registries and image_signing_pubkey_pem go together (no unsigned registries)")
        if self.image_signing_pubkey_pem:
            if self.image_signing_key_sha256 is None or not HEX64.match(self.image_signing_key_sha256):
                raise ValueError("image_signing_key_sha256 (pinned fingerprint) is required")
            try:
                der = serialization.load_pem_public_key(self.image_signing_pubkey_pem.encode()).public_bytes(
                    serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
            except ValueError as e:
                raise ValueError("image_signing_pubkey_pem is not a PEM public key") from e
            if hashlib.sha256(der).hexdigest() != self.image_signing_key_sha256:
                raise ValueError("image signing key does not match its pinned fingerprint")
        if hashlib.sha256(base64.b64decode(self.agent_bundle_b64, validate=True)).hexdigest() != self.agent_bundle_sha256:
            raise ValueError("agent bundle does not match its sha256")
        if self.pkg_allowlist and not self.ou_repo:
            raise ValueError("pkg_allowlist needs ou_repo (packages come from the allowlisted repository only)")
        return self


def build_agent_bundle(agent_dir: str) -> bytes:
    """Deterministic tar.gz of the node agent (ou_agent/ + deploy/ files laid out the way install-agent.sh expects)."""
    entries = []
    for root, _, files in os.walk(os.path.join(agent_dir, "ou_agent")):
        for f in files:
            if f.endswith(".py"):
                p = os.path.join(root, f)
                entries.append((os.path.relpath(p, agent_dir), p))
    dep = os.path.join(agent_dir, "deploy")
    for f in ("install-agent.sh", "ou-agent.service", "render_polkit.py", "render_image_policy.py"):
        entries.append((f, os.path.join(dep, f)))
    for f in os.listdir(os.path.join(dep, "runbooks")):
        if f.startswith("ou-rb-podman@") or f.startswith("ou-rb-pkg@"):
            entries.append(("runbooks/" + f, os.path.join(dep, "runbooks", f)))
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as t:
        for arc, p in sorted(entries):
            data = open(p, "rb").read()
            ti = tarfile.TarInfo(arc)
            ti.size, ti.mtime, ti.mode, ti.uid, ti.gid, ti.uname, ti.gname = len(data), 0, 0o755 if arc.endswith((".sh", ".py")) else 0o644, 0, 0, "root", "root"
            t.addfile(ti, io.BytesIO(data))
    return gzip.compress(raw.getvalue(), mtime=0)


def agent_config(s: GuestSpec) -> dict:
    rb = {"disk.usage": {"paths": ["/", SERVICE_HOME]}, "guest.facts": {"enabled": True}, "podman.status": {"enabled": True},
          "podman.remove_unit": {"enabled": True}}
    if s.image_registries:
        rb["podman.pull_verified"] = {"registries": sorted(s.image_registries)}
        rb["podman.deploy_unit"] = {"registries": sorted(s.image_registries)}
    if s.pkg_allowlist:
        rb["pkg.install_pinned"] = {"packages": sorted(s.pkg_allowlist)}
    return {"listen": {"address": "0.0.0.0", "port": s.agent_port}, "runbooks": dict(sorted(rb.items()))}


def nftables_ruleset(s: GuestSpec) -> str:
    def saddr(cidrs):
        v4 = [c for c in cidrs if ":" not in c]
        v6 = [c for c in cidrs if ":" in c]
        return v4, v6

    rules = ["    ct state established,related accept", "    ct state invalid drop", '    iif "lo" accept',
             "    ip protocol icmp icmp type { echo-request, destination-unreachable, time-exceeded } accept",
             "    meta l4proto ipv6-icmp accept", "    udp sport 67 udp dport 68 accept", "    udp sport 547 udp dport 546 accept"]

    def add(port, proto, cidrs):
        if not cidrs:
            rules.append(f"    {proto} dport {port} accept")
            return
        v4, v6 = saddr(cidrs)
        if v4:
            rules.append(f"    ip saddr {{ {', '.join(v4)} }} {proto} dport {port} accept")
        if v6:
            rules.append(f"    ip6 saddr {{ {', '.join(v6)} }} {proto} dport {port} accept")
    add(s.agent_port, "tcp", s.mgmt_sources)
    if s.break_glass_ssh_key:
        add(22, "tcp", s.mgmt_sources)
    for p in sorted(s.declared_ports, key=lambda x: (x.port, x.proto)):
        add(p.port, p.proto, p.sources)
    return ("#!/usr/sbin/nft -f\n# generated by Office Unbound (guest bootstrap): default deny inbound; only declared ports\nflush ruleset\n"
            "table inet ou_guest {\n  chain input {\n    type filter hook input priority 0; policy drop;\n" + "\n".join(rules) +
            "\n  }\n  chain forward {\n    type filter hook forward priority 0; policy drop;\n  }\n  chain output {\n"
            "    type filter hook output priority 0; policy accept;\n  }\n}\n")


def unattended_conf(s: GuestSpec) -> tuple[str, str]:
    distro = SUITES[s.os][0]
    on = "1" if s.unattended == "security" else "0"
    auto = f'APT::Periodic::Update-Package-Lists "1";\nAPT::Periodic::Unattended-Upgrade "{on}";\n'
    origin = ('"${distro_id}:${distro_codename}-security";\n  "${distro_id}ESMApps:${distro_codename}-apps-security";'
              if distro == "ubuntu" else '"origin=Debian,codename=${distro_codename}-security,label=Debian-Security";')
    uu = ("// generated: security updates only; never reboots by itself (maintenance windows are an ICS decision)\n"
          f"Unattended-Upgrade::Allowed-Origins {{\n  {origin}\n}};\nUnattended-Upgrade::Automatic-Reboot \"false\";\n"
          "Unattended-Upgrade::Remove-Unused-Dependencies \"false\";\n")
    return auto, uu


def apt_sources(s: GuestSpec) -> str:
    distro, suite = SUITES[s.os]
    mirror = {"ubuntu": ("http://archive.ubuntu.com/ubuntu", "http://security.ubuntu.com/ubuntu", "main universe"),
              "debian": ("http://deb.debian.org/debian", "http://deb.debian.org/debian-security", "main")}[distro]
    kr = KEYRING[distro]
    lines = [f"deb [signed-by={kr}] {mirror[0]} {suite} {mirror[2]}", f"deb [signed-by={kr}] {mirror[0]} {suite}-updates {mirror[2]}",
             f"deb [signed-by={kr}] {mirror[1]} {suite}-security {mirror[2]}" if distro == "ubuntu" else
             f"deb [signed-by={kr}] {mirror[1]} {suite}-security {mirror[2]}"]
    if s.ou_repo:
        lines.append(f"deb [signed-by=/etc/ou-agent/apt/keyrings/ou-repo.asc] {s.ou_repo.url} {s.ou_repo.suite} {' '.join(s.ou_repo.components)}")
    return "# generated: the ONLY sources pkg.install_pinned uses (system sources are not consulted)\n" + "\n".join(lines) + "\n"


def bootstrap_script(s: GuestSpec) -> str:
    q = shlex.quote
    fqdn = f"{s.hostname}.{s.domain}" if s.domain else s.hostname
    addr = f"ADDR={q(s.agent_address)}" if s.agent_address else \
        "ADDR=$(ip -4 -o addr show scope global | awk '{print $4}' | cut -d/ -f1 | head -n1)"
    ssh_on = bool(s.break_glass_ssh_key)
    ssh = ("install -d -m 0755 /etc/ssh/sshd_config.d\nprintf 'PasswordAuthentication no\\nKbdInteractiveAuthentication no\\nPermitRootLogin no\\n"
           f"AllowUsers {BREAK_GLASS_USER}\\n' > /etc/ssh/sshd_config.d/10-ou-breakglass.conf\nsystemctl enable --now ssh.service 2>/dev/null || systemctl enable --now ssh.socket"
           if ssh_on else "systemctl disable --now ssh.socket ssh.service 2>/dev/null || true\nsystemctl mask ssh.socket ssh.service 2>/dev/null || true")
    return f"""#!/bin/sh
# generated by Office Unbound guest bootstrap; idempotent. Contains no secret (enrollment is armed with a token HASH).
set -eu
umask 022
B=/var/lib/ou-bootstrap
[ -f $B/done ] && exit 0
export DEBIAN_FRONTEND=noninteractive
hostnamectl set-hostname {q(fqdn)} 2>/dev/null || hostname {q(s.hostname)}
# --- rootless workload user: subuid/subgid + linger (user manager runs without a login)
# useradd may already have allocated a default range (outside what a nested/nspawn user namespace owns): the declared one replaces it
# (edited directly: usermod refuses while the user's manager runs, which makes this idempotent on re-runs)
sed -i '/^{SERVICE_USER}:/d' /etc/subuid /etc/subgid
echo '{SERVICE_USER}:{s.subid_start}:{s.subid_count}' | tee -a /etc/subuid >> /etc/subgid
loginctl enable-linger {SERVICE_USER}
# --- firewall: default deny inbound, declared ports only (syntax checked before it is applied)
nft -c -f /etc/nftables.conf
systemctl enable nftables.service
nft -f /etc/nftables.conf
# --- SSH
{ssh}
# --- pinned supply-chain inputs for the agent runbooks (root-owned, not writable by the agent or the service user)
chown -R root:root /etc/ou-agent; chmod -R go-w /etc/ou-agent
# --- node agent from the embedded, hash-verified bundle
echo {q(s.agent_bundle_sha256 + "  " + "/var/lib/ou-bootstrap/agent.tar.gz")} | sha256sum -c - >/dev/null
rm -rf $B/agent; install -d -m 0700 $B/agent
tar -xzf $B/agent.tar.gz -C $B/agent --no-same-owner
cp /etc/ou-agent/agent.src.json $B/agent/agent-guest.json
{addr}
OU_ENROLL_TOKEN_SHA256={q(s.enroll_token_sha256)} OU_ENROLL_TTL={s.enroll_ttl_seconds} sh $B/agent/install-agent.sh "$ADDR" {q(s.hostname)} agent-guest.json >$B/install.log 2>&1 || {{ tail -n 20 $B/install.log >&2; exit 1; }}
# public fingerprints for the operator / ICS (read through the hypervisor guest agent or console); never the token
TLS=$(setpriv --reuid=ou-agent --regid=ou-agent --clear-groups env PYTHONPATH=/opt/ou-agent PYTHONDONTWRITEBYTECODE=1 python3 -m ou_agent show | sed -n 's/^tls_fingerprint_sha256=//p')
KEY=$(setpriv --reuid=ou-agent --regid=ou-agent --clear-groups env PYTHONPATH=/opt/ou-agent PYTHONDONTWRITEBYTECODE=1 python3 -m ou_agent show | sed -n 's/^agent_key_fingerprint_sha256=//p')
printf '{{"address":"%s","port":{s.agent_port},"tls_fingerprint_sha256":"%s","agent_key_fingerprint_sha256":"%s"}}\\n' "$ADDR" "$TLS" "$KEY" > $B/fingerprints.json
chmod 0644 $B/fingerprints.json
echo "OU-AGENT-FINGERPRINTS $(cat $B/fingerprints.json)" > /dev/console 2>/dev/null || true
touch $B/done
"""


def _wf(path, content, mode="0644", b64=False):
    d = {"path": path, "owner": "root:root", "permissions": mode, "content": content}
    if b64:
        d["encoding"] = "b64"
    return d


def build(s: GuestSpec) -> dict:
    distro, _ = SUITES[s.os]
    auto, uu = unattended_conf(s)
    files = [
        _wf("/etc/nftables.conf", nftables_ruleset(s)),
        _wf("/etc/apt/apt.conf.d/20auto-upgrades", auto),
        _wf("/etc/apt/apt.conf.d/52ou-unattended-upgrades", uu),
        _wf("/etc/ou-agent/agent.src.json", json.dumps(agent_config(s), indent=2) + "\n"),
        _wf("/var/lib/ou-bootstrap/agent.tar.gz", s.agent_bundle_b64, "0600", b64=True),
        _wf("/usr/local/sbin/ou-guest-bootstrap", bootstrap_script(s), "0750"),
    ]
    if s.image_signing_pubkey_pem:
        files.append(_wf("/etc/ou-agent/image-signing.pub", s.image_signing_pubkey_pem if s.image_signing_pubkey_pem.endswith("\n") else s.image_signing_pubkey_pem + "\n"))
    if s.ou_repo:
        files += [_wf("/etc/ou-agent/apt/sources.list", apt_sources(s)),
                  _wf("/etc/ou-agent/apt/keyrings/ou-repo.asc", s.ou_repo.key_armored if s.ou_repo.key_armored.endswith("\n") else s.ou_repo.key_armored + "\n"),
                  _wf("/etc/ou-agent/apt/pinned-fingerprints", "# pinned OpenPGP fingerprints; pkg.install_pinned refuses any other key\n" + s.ou_repo.key_fingerprint + "\n")]
    elif s.pkg_allowlist:
        raise ValueError("pkg_allowlist without ou_repo")
    users = [{"name": SERVICE_USER, "gecos": "Office Unbound workload (rootless Podman)", "homedir": SERVICE_HOME, "shell": "/usr/sbin/nologin",
              "lock_passwd": True, "system": False}]
    if s.break_glass_ssh_key:
        users.append({"name": BREAK_GLASS_USER, "gecos": "break-glass (key only)", "shell": "/bin/bash", "lock_passwd": True,
                      "ssh_authorized_keys": [s.break_glass_ssh_key], "sudo": "ALL=(ALL) NOPASSWD:ALL"})
    packages = sorted(set(BASE_PACKAGES) | set(s.extra_packages) | ({"openssh-server"} if s.break_glass_ssh_key else set()))
    cfg = {
        "hostname": s.hostname, "fqdn": f"{s.hostname}.{s.domain}" if s.domain else s.hostname,
        "prefer_fqdn_over_hostname": False, "manage_etc_hosts": True, "timezone": s.timezone,
        "disable_root": True, "ssh_pwauth": False, "users": users,
        "ntp": {"enabled": True, "ntp_client": "systemd-timesyncd", **({"servers": s.ntp_servers} if s.ntp_servers else {})},
        "package_update": True, "package_upgrade": False, "packages": packages,
        "write_files": files,
        "runcmd": [["/usr/local/sbin/ou-guest-bootstrap"]],
        "final_message": "Office Unbound guest bootstrap finished after $UPTIME seconds",
    }
    return cfg


def render(s: GuestSpec) -> str:
    return "#cloud-config\n" + yaml.safe_dump(build(s), sort_keys=True, default_flow_style=False, width=1000)
