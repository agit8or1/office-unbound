"""cloud-init user-data renderer for Office Unbound guests (ADR-0009 section 5). `render(spec) -> str` is a pure, deterministic function:
same spec -> same bytes. The output contains NO secret: the enrollment token is generated by the ICS and only its SHA-256 is given to the
guest (the agent stores only the hash anyway), so nothing sensitive reaches user-data, the hypervisor snippet store, /var/lib/cloud or any log.
Every value interpolated into the bootstrap script has passed a closed-shape validator and is shlex-quoted as well."""
