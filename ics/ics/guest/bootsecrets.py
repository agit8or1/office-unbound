"""Per-VM-INSTANCE one-time bootstrap secrets (bootstrap review M1).

Every VM instance (deployment, vm name, vmid) gets fresh random material: a proof secret (SMBIOS), and for the lab SSH bootstrap an Ed25519
key and an agent-enrollment token. Nothing is derived from the ICS signing key, so nothing is recomputable and a re-created VM never shares
material with its predecessor. Values are vault-encrypted (AAD binds the row and the column) and DELETED (columns set to NULL) once the bootstrap
is over; a replaced instance's record is revoked and wiped. Only `bid` (a public, random lookup id, carried in the SMBIOS serial) is not secret."""
import base64
import hashlib
import secrets
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from sqlalchemy import text

LIVE = ("pending", "reported", "enrolled")


@dataclass(frozen=True)
class BootRecord:
    id: str
    bid: str                        # 16 hex, public lookup id
    deployment_id: str
    vm: str
    vmid: int
    mode: str
    secret: str | None              # 64 hex (callback) / 48 hex (ssh-lab proof key); None once deleted
    ssh_private_openssh: bytes | None
    ssh_public: str | None
    token: str | None               # one-time agent enrollment token (ssh-lab only; the callback flow's token is generated by the guest)
    state: str
    expires_at: datetime

    @property
    def token_sha256(self) -> str | None:
        return hashlib.sha256(self.token.encode()).hexdigest() if self.token else None

    @property
    def smbios_serial(self) -> str:   # [0-9a-f]{16}+secret, matches the provider's serial pattern
        return self.bid + (self.secret or "")


def _ctx(rid: str, col: str) -> str:
    return f"guest_bootstrap:{rid}:{col}"


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _row_to_record(rt, r) -> BootRecord:
    rid = str(r.id)
    dec = lambda blob, col: rt.vault.decrypt(blob, _ctx(rid, col)) if blob is not None else None  # noqa: E731
    secret, key, tok = dec(r.secret_enc, "secret"), dec(r.ssh_key_enc, "ssh"), dec(r.token_enc, "token")
    pub = None
    if key:
        pub = serialization.load_ssh_private_key(key, None).public_key().public_bytes(
            serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH).decode() + " ou-bootstrap"
    return BootRecord(rid, r.bid, str(r.deployment_id), r.vm, r.vmid, r.mode, secret.decode() if secret else None, key, pub,
                      tok.decode() if tok else None, r.state, r.expires_at)


def issue(rt, deployment_id: str, vm: str, vmid: int, mode: str, ttl_seconds: int | None = None) -> BootRecord:
    """The live record of this exact instance (idempotent for resumes), or a fresh one. Records of OTHER instances of the same VM are revoked and wiped."""
    ttl = ttl_seconds or rt.settings.guest_bootstrap_ttl_seconds
    with rt.session() as db:
        rows = db.execute(text("SELECT * FROM guest_bootstrap WHERE deployment_id = :d AND vm = :v AND state = ANY(:s) AND secret_enc IS NOT NULL "
                               "ORDER BY created_at DESC FOR UPDATE"), {"d": deployment_id, "v": vm, "s": list(LIVE)}).all()
        for r in rows:
            if r.vmid == vmid and r.mode == mode and r.expires_at > _now() and r.state == "pending":
                return _row_to_record(rt, r)
        for r in rows:   # a different instance, a different mode or an expired attempt: its material is dead
            db.execute(text("UPDATE guest_bootstrap SET state = 'revoked', secret_enc = NULL, ssh_key_enc = NULL, token_enc = NULL, "
                            "secret_deleted_at = now() WHERE id = :i"), {"i": str(r.id)})
        import uuid
        rid = str(uuid.uuid4())
        bid = secrets.token_hex(8)
        secret = (secrets.token_hex(24) if mode == "ssh-lab" else secrets.token_hex(32)).encode()
        key = tok = None
        if mode == "ssh-lab":
            key = Ed25519PrivateKey.generate().private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH, serialization.NoEncryption())
            tok = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode().rstrip("=").encode()
        enc = lambda v, col: rt.vault.encrypt(v, _ctx(rid, col)) if v is not None else None  # noqa: E731
        db.execute(text("INSERT INTO guest_bootstrap (id, bid, deployment_id, vm, vmid, mode, secret_enc, ssh_key_enc, token_enc, expires_at) "
                        "VALUES (:i, :b, :d, :v, :m, :mode, :s, :k, :t, :e)"),
                   {"i": rid, "b": bid, "d": deployment_id, "v": vm, "m": vmid, "mode": mode, "s": enc(secret, "secret"), "k": enc(key, "ssh"),
                    "t": enc(tok, "token"), "e": _now() + timedelta(seconds=ttl)})
        db.commit()
        r = db.execute(text("SELECT * FROM guest_bootstrap WHERE id = :i"), {"i": rid}).first()
    return _row_to_record(rt, r)


def find(rt, deployment_id: str, vm: str, vmid: int, mode: str | None = None) -> BootRecord | None:
    """Latest record of this instance, secrets included while they exist."""
    with rt.session() as db:
        r = db.execute(text("SELECT * FROM guest_bootstrap WHERE deployment_id = :d AND vm = :v AND vmid = :m AND (CAST(:mode AS text) IS NULL OR mode = :mode) "
                            "ORDER BY created_at DESC LIMIT 1"), {"d": deployment_id, "v": vm, "m": vmid, "mode": mode}).first()
    return _row_to_record(rt, r) if r else None


def by_bid(rt, bid: str):
    with rt.session() as db:
        return db.execute(text("SELECT * FROM guest_bootstrap WHERE bid = :b"), {"b": bid}).first()


def set_state(rt, rid: str, state: str, **cols) -> None:
    sets = ["state = :st"] + [f"{k} = :{k}" for k in cols]
    with rt.session() as db:
        db.execute(text(f"UPDATE guest_bootstrap SET {', '.join(sets)} WHERE id = :i"), {"st": state, "i": rid, **cols})
        db.commit()


def delete_secrets(rt, rid: str, state: str) -> None:
    """The bootstrap is over: wipe every secret column (the row stays as the audit trail)."""
    with rt.session() as db:
        db.execute(text("UPDATE guest_bootstrap SET secret_enc = NULL, ssh_key_enc = NULL, token_enc = NULL, secret_deleted_at = now(), state = :s, "
                        "sealed_at = CASE WHEN :s = 'sealed' THEN now() ELSE sealed_at END WHERE id = :i"), {"s": state, "i": rid})
        db.commit()


def secrets_wiped(rt, rid: str) -> bool:
    with rt.session() as db:
        return bool(db.execute(text("SELECT secret_enc IS NULL AND ssh_key_enc IS NULL AND token_enc IS NULL FROM guest_bootstrap WHERE id = :i"),
                               {"i": rid}).scalar())
