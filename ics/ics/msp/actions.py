"""Typed plan actions that manage MSP API clients (ADR-0013). Every one is admin-only, high risk (two human approvers).

A client's HMAC key is generated by the executor (never part of a plan, never in the audit log), stored vault-encrypted, and handed to the
plan's requester exactly once through the console (`reveal`). An API client can never create, change, rotate or revoke API clients."""
import json
import secrets
from datetime import datetime, timedelta, timezone
from typing import Literal, Self
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, model_validator
from sqlalchemy import text

from .. import audit, auth

PERMISSIONS = ("view", "plan", "approve", "execute")
ELEVATED = {"approve", "execute"}
Perm = Literal["view", "plan", "approve", "execute"]
REVEAL_TTL = timedelta(hours=24)
MAX_GRACE = 7 * 24 * 3600


class _Scope(BaseModel):
    all_customers: bool = False
    customer_ids: list[UUID] = Field(default_factory=list, max_length=500)

    def _scope_ok(self) -> None:
        if self.all_customers and self.customer_ids:
            raise ValueError("all_customers excludes customer_ids")
        if not self.all_customers and not self.customer_ids:
            raise ValueError("give customer_ids or all_customers=true")


class ClientCreate(_Scope):
    model_config = ConfigDict(extra="forbid")
    name: str = Field(pattern=r"^[A-Za-z0-9][A-Za-z0-9 _.&()-]{0,99}$")
    permissions: list[Perm] = Field(default_factory=lambda: ["view", "plan"], min_length=1, max_length=4)
    mtls_fingerprint_sha256: str | None = Field(default=None, pattern=r"^[0-9a-fA-F:]{64,95}$",
                                                description="optional: require this client certificate (SHA-256) forwarded by the trusted TLS proxy")
    rate_limit_per_minute: int = Field(default=120, ge=1, le=6000)
    acknowledge_elevated: bool = Field(default=False, description="must be true when 'approve' or 'execute' is granted (policy-approved auto-approval)")

    @model_validator(mode="after")
    def _v(self) -> Self:
        self._scope_ok()
        _elevated_ack(self.permissions, self.acknowledge_elevated)
        self.permissions = sorted(set(self.permissions), key=PERMISSIONS.index)
        return self


class ClientSetPermissions(_Scope):
    model_config = ConfigDict(extra="forbid")
    client_id: str = Field(pattern=r"^mspc_[0-9a-f]{16}$")
    permissions: list[Perm] = Field(min_length=1, max_length=4)
    rate_limit_per_minute: int | None = Field(default=None, ge=1, le=6000)
    acknowledge_elevated: bool = False

    @model_validator(mode="after")
    def _v(self) -> Self:
        self._scope_ok()
        _elevated_ack(self.permissions, self.acknowledge_elevated)
        self.permissions = sorted(set(self.permissions), key=PERMISSIONS.index)
        return self


class ClientRotate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    client_id: str = Field(pattern=r"^mspc_[0-9a-f]{16}$")
    grace_seconds: int = Field(default=86400, ge=0, le=MAX_GRACE, description="the previous key keeps working this long (0 = cut over immediately)")


class ClientRevoke(BaseModel):
    model_config = ConfigDict(extra="forbid")
    client_id: str = Field(pattern=r"^mspc_[0-9a-f]{16}$")


class StackLink(BaseModel):
    model_config = ConfigDict(extra="forbid")
    stack: str = Field(pattern=r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,62}$", description="registered identity stack")
    customer_id: UUID


def _elevated_ack(perms, ack: bool) -> None:
    if ELEVATED & set(perms) and not ack:
        raise ValueError("granting 'approve' or 'execute' lets this client approve/auto-run low-risk plans on MSP-owned customers; "
                         "set acknowledge_elevated=true to confirm that the approvers have reviewed this")


def _client(db, client_id: str):
    from ..actions import PlanError
    c = db.execute(text("SELECT * FROM msp_clients WHERE client_id = :c"), {"c": client_id}).first()
    if c is None:
        raise PlanError(404, "API client not found")
    return c


def precheck(db, rt, action: str, p) -> dict:
    from ..actions import PlanError
    if action == "msp.client.create":
        if db.execute(text("SELECT 1 FROM msp_clients WHERE name = :n AND status = 'active'"), {"n": p.name}).first():
            raise PlanError(409, "an active API client with this name already exists")
    elif action == "msp.stack.link":
        if not db.execute(text("SELECT 1 FROM idm_stacks WHERE name = :n"), {"n": p.stack}).first():
            raise PlanError(404, "stack not found")
        if not db.execute(text("SELECT 1 FROM customers WHERE id = :c"), {"c": str(p.customer_id)}).first():
            raise PlanError(404, "customer not found")
        return {"customer_id": str(p.customer_id)}
    else:
        c = _client(db, p.client_id)
        if c.status != "active":
            raise PlanError(409, "API client is revoked")
    ids = getattr(p, "customer_ids", None)
    if ids:
        n = db.execute(text("SELECT count(*) FROM customers WHERE id = ANY(CAST(:c AS uuid[]))"), {"c": [str(i) for i in ids]}).scalar()
        if n != len(set(ids)):
            raise PlanError(404, "customer not found")
    return {}


def new_secret() -> str:
    return "mspk_" + secrets.token_urlsafe(32)


def secret_ctx(row_id, version: int) -> str:
    return f"msp-client:{row_id}:{version}"


def _set_scope(db, row, uid, all_customers: bool, customer_ids) -> None:
    db.execute(text("UPDATE users SET all_customers = :a WHERE id = :u"), {"a": all_customers, "u": str(uid)})
    db.execute(text("DELETE FROM operator_customers WHERE user_id = :u"), {"u": str(uid)})
    db.execute(text("DELETE FROM msp_client_customers WHERE client_id = :c"), {"c": str(row)})
    for cid in sorted(set(customer_ids)):
        db.execute(text("INSERT INTO operator_customers (user_id, customer_id) VALUES (:u, :c)"), {"u": str(uid), "c": str(cid)})
        db.execute(text("INSERT INTO msp_client_customers (client_id, customer_id) VALUES (:r, :c)"), {"r": str(row), "c": str(cid)})


def _reveal(rt, db, plan, row_id, client_id: str, secret: str, version: int) -> None:
    blob = rt.vault.encrypt(json.dumps({"client_id": client_id, "secret": secret, "secret_version": version}).encode(), f"msp-reveal:{plan.id}")
    db.execute(text("INSERT INTO msp_client_reveals (plan_id, client_id, requested_by, secret_enc, expires_at) VALUES (:p, :c, :u, :s, :e)"),
               {"p": str(plan.id), "c": str(row_id), "u": str(plan.requested_by), "s": blob, "e": datetime.now(timezone.utc) + REVEAL_TTL})


def exec_create(rt, db, m: ClientCreate, plan, known):
    client_id = "mspc_" + secrets.token_hex(8)
    secret = new_secret()
    known.append(secret)
    uid = auth.create_invite(db, rt, "msp-" + client_id[5:], "operator", created_by=plan.requested_by, actor="worker", commit=False,
                             extra={"msp_client": client_id})
    db.execute(text("UPDATE users SET disabled = true WHERE id = :u"), {"u": uid})  # a service principal: it can never hold a console session
    rid = db.execute(text(
        "INSERT INTO msp_clients (client_id, name, user_id, permissions, all_customers, mtls_fingerprint, rate_limit_per_minute, created_by, created_plan_id) "
        "VALUES (:c, :n, :u, :p, :a, :m, :r, :cb, :pl) RETURNING id"),
        {"c": client_id, "n": m.name, "u": uid, "p": list(m.permissions), "a": m.all_customers,
         "m": m.mtls_fingerprint_sha256.replace(":", "").lower() if m.mtls_fingerprint_sha256 else None, "r": m.rate_limit_per_minute,
         "cb": str(plan.requested_by), "pl": str(plan.id)}).scalar()
    db.execute(text("UPDATE msp_clients SET secret_enc = :s WHERE id = :i"), {"s": rt.vault.encrypt(secret.encode(), secret_ctx(rid, 1)), "i": rid})
    _set_scope(db, rid, uid, m.all_customers, m.customer_ids)
    _reveal(rt, db, plan, rid, client_id, secret, 1)
    audit.append(db, "msp.client.created", actor_name="worker", resource="msp_client", resource_id=str(rid),
                 details={"client_id": client_id, "name": m.name, "permissions": list(m.permissions), "all_customers": m.all_customers,
                          "customer_ids": sorted(str(c) for c in m.customer_ids), "mtls": bool(m.mtls_fingerprint_sha256)})
    return {"client_id": client_id, "reveal": "requester: POST /api/v1/msp/clients/{plan_id}/reveal (once, 24h)"}


def exec_set_permissions(rt, db, m: ClientSetPermissions, plan, known):
    c = db.execute(text("SELECT * FROM msp_clients WHERE client_id = :c FOR UPDATE"), {"c": m.client_id}).first()
    if c is None or c.status != "active":
        raise ValueError("API client not found or revoked")
    db.execute(text("UPDATE msp_clients SET permissions = :p, all_customers = :a, rate_limit_per_minute = COALESCE(:r, rate_limit_per_minute) WHERE id = :i"),
               {"p": list(m.permissions), "a": m.all_customers, "r": m.rate_limit_per_minute, "i": str(c.id)})
    _set_scope(db, c.id, c.user_id, m.all_customers, m.customer_ids)
    audit.append(db, "msp.client.permissions_set", actor_name="worker", resource="msp_client", resource_id=str(c.id),
                 details={"client_id": m.client_id, "from": list(c.permissions), "to": list(m.permissions), "all_customers": m.all_customers,
                          "customer_ids": sorted(str(x) for x in m.customer_ids)})
    return {"client_id": m.client_id, "permissions": list(m.permissions)}


def exec_rotate(rt, db, m: ClientRotate, plan, known):
    c = db.execute(text("SELECT * FROM msp_clients WHERE client_id = :c FOR UPDATE"), {"c": m.client_id}).first()
    if c is None or c.status != "active":
        raise ValueError("API client not found or revoked")
    secret = new_secret()
    known.append(secret)
    v = c.secret_version + 1
    grace = datetime.now(timezone.utc) + timedelta(seconds=m.grace_seconds)
    db.execute(text("UPDATE msp_clients SET prev_secret_enc = CASE WHEN :g > 0 THEN secret_enc END, prev_secret_version = CASE WHEN :g > 0 THEN secret_version END, "
                    "prev_secret_expires_at = CASE WHEN :g > 0 THEN :e END, secret_enc = :s, secret_version = :v WHERE id = :i"),
               {"g": m.grace_seconds, "e": grace, "s": rt.vault.encrypt(secret.encode(), secret_ctx(c.id, v)), "v": v, "i": str(c.id)})
    _reveal(rt, db, plan, c.id, m.client_id, secret, v)
    audit.append(db, "msp.client.rotated", actor_name="worker", resource="msp_client", resource_id=str(c.id),
                 details={"client_id": m.client_id, "secret_version": v, "grace_seconds": m.grace_seconds})
    return {"client_id": m.client_id, "secret_version": v}


def exec_revoke(rt, db, m: ClientRevoke, plan, known):
    c = db.execute(text("SELECT * FROM msp_clients WHERE client_id = :c FOR UPDATE"), {"c": m.client_id}).first()
    if c is None:
        raise ValueError("API client not found")
    db.execute(text("UPDATE msp_clients SET status = 'revoked', revoked_at = now(), secret_enc = NULL, prev_secret_enc = NULL, prev_secret_expires_at = NULL "
                    "WHERE id = :i"), {"i": str(c.id)})
    db.execute(text("UPDATE msp_webhooks SET enabled = false, deleted_at = now() WHERE client_id = :i AND deleted_at IS NULL"), {"i": str(c.id)})
    db.execute(text("UPDATE msp_deliveries SET status = 'dead', last_error = 'client revoked' WHERE status = 'pending' AND webhook_id IN "
                    "(SELECT id FROM msp_webhooks WHERE client_id = :i)"), {"i": str(c.id)})
    db.execute(text("UPDATE msp_client_reveals SET secret_enc = NULL WHERE client_id = :i"), {"i": str(c.id)})
    audit.append(db, "msp.client.revoked", actor_name="worker", resource="msp_client", resource_id=str(c.id), details={"client_id": m.client_id})
    return {"client_id": m.client_id, "status": "revoked"}


def exec_stack_link(rt, db, m: StackLink, plan, known):
    db.execute(text("UPDATE idm_stacks SET customer_id = :c WHERE name = :n"), {"c": str(m.customer_id), "n": m.stack})
    audit.append(db, "msp.stack.linked", actor_name="worker", resource="idm_stack", resource_id=m.stack, details={"customer_id": str(m.customer_id)})
    return {"stack": m.stack, "customer_id": str(m.customer_id)}


def reveal(db, rt, user, plan_id) -> dict:
    """Console API: the plan's REQUESTER sees the key exactly once; the ciphertext is wiped in the same transaction."""
    row = db.execute(text("SELECT * FROM msp_client_reveals WHERE plan_id = :p AND requested_by = :u AND secret_enc IS NOT NULL AND revealed_at IS NULL "
                          "AND expires_at > now() FOR UPDATE"), {"p": str(plan_id), "u": str(user.id)}).first()
    if row is None:
        return {}
    data = json.loads(rt.vault.decrypt(row.secret_enc, f"msp-reveal:{plan_id}"))
    db.execute(text("UPDATE msp_client_reveals SET secret_enc = NULL, revealed_at = now() WHERE plan_id = :p"), {"p": str(plan_id)})
    audit.append(db, "msp.client.secret_revealed", actor_id=user.id, actor_name=user.username, resource="msp_client", resource_id=str(row.client_id),
                 details={"client_id": data["client_id"], "plan_id": str(plan_id), "secret_version": data["secret_version"]})
    db.commit()
    return {**data, "note": "shown once; store it in the integration's secret store. Sign requests as documented in docs/api/msp-v1.yaml"}


SPECS = {k: {"model": v, "risk": "high", "secrets": (), "admin_only": True} for k, v in {
    "msp.client.create": ClientCreate, "msp.client.set_permissions": ClientSetPermissions, "msp.client.rotate": ClientRotate,
    "msp.client.revoke": ClientRevoke, "msp.stack.link": StackLink}.items()}
EXECUTORS = {"msp.client.create": exec_create, "msp.client.set_permissions": exec_set_permissions, "msp.client.rotate": exec_rotate,
             "msp.client.revoke": exec_revoke, "msp.stack.link": exec_stack_link}
PRECHECK = {k: (lambda db, rt, p, _k=k: precheck(db, rt, _k, p)) for k in SPECS}
