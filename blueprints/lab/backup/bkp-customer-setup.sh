#!/usr/bin/env bash
# Office Unbound lab: PER-CUSTOMER backup target on the backup machine (T20 / agent AU). Idempotent.
# Usage: sudo bkp-customer-setup.sh <customer-profile> [<customer-profile> ...]     (profile = c-<32 hex>, derived from the ICS customer id)
# Requires bkp-target-setup.sh to have been run (rest-server binary, TLS certificate, restsrv user).
# Adds two NEW rest-server listeners on a SEPARATE repository store (/srv/restic-cust), next to the legacy ones (:8000/:8001 untouched):
#   :8010  --append-only --private-repos    what the customers' backup runners use: add snapshots/packs, cannot delete or overwrite history
#   :8011  --private-repos                  maintenance (forget/prune) only
# --private-repos: the authenticated user can only reach /<user>/..., so customer c-X (REST user = profile) cannot even see /c-Y/. Credentials differ per
# customer AND per listener; the htpasswd files hold bcrypt hashes only; the plaintext goes to <secrets_dir>/cust/<profile>/rest-{backup,maint}.pw (root 0600).
# The customers' restic repository PASSWORDS are a different secret (generated by the ICS vault, bound to the customer); the REST credential only
# controls access to the storage path, it does not decrypt anything.
set -euo pipefail
M="${OU_BKP_MACHINE:-ou-bkp1}"; SD="${OU_BKP_SECRETS:-/etc/office-unbound/backup-lab}"
[ "$#" -ge 1 ] || { echo "usage: $0 <profile> ..." >&2; exit 2; }
for p in "$@"; do [[ "$p" =~ ^c-[0-9a-f]{32}$ ]] || { echo "bad profile $p" >&2; exit 2; }; done
in_m() { systemd-run -M "$M" --wait -q -P --pipe /bin/bash -c "$1"; }
put() { in_m "cat > '$1' && chmod $2 '$1'"; }
in_m "test -x /usr/local/bin/rest-server && test -f /etc/rest-server/tls.crt" || { echo "run bkp-target-setup.sh first" >&2; exit 1; }
in_m "install -d -o restsrv -g restsrv -m 0700 /srv/restic-cust"
HT_B="$(mktemp)"; HT_M="$(mktemp)"; trap 'rm -f "$HT_B" "$HT_M"' EXIT
for p in "$@"; do
  d="$SD/cust/$p"; install -d -m 0700 "$d"
  for k in backup maint; do [ -s "$d/rest-$k.pw" ] || ( umask 077; openssl rand -hex 24 > "$d/rest-$k.pw" ); done
  python3 -c 'import bcrypt,sys; print(sys.argv[1] + ":" + bcrypt.hashpw(sys.stdin.read().strip().encode(), bcrypt.gensalt(12)).decode())' "$p" < "$d/rest-backup.pw" >> "$HT_B"
  python3 -c 'import bcrypt,sys; print(sys.argv[1] + ":" + bcrypt.hashpw(sys.stdin.read().strip().encode(), bcrypt.gensalt(12)).decode())' "$p" < "$d/rest-maint.pw" >> "$HT_M"
done
# (the files are rewritten from the full set of profiles given: customers not listed lose access; rest-server re-reads htpasswd on SIGHUP)
cat "$HT_B" | put /etc/rest-server/htpasswd-cust-backup 0640
cat "$HT_M" | put /etc/rest-server/htpasswd-cust-maint 0640
in_m "chgrp restsrv /etc/rest-server/htpasswd-cust-*"
unit() { # name port extra
cat <<UNIT
[Unit]
Description=restic rest-server per-customer ($1)
After=network-online.target
[Service]
User=restsrv
ExecStart=/usr/local/bin/rest-server --path /srv/restic-cust --listen :$2 --tls --tls-cert /etc/rest-server/tls.crt --tls-key /etc/rest-server/tls.key --htpasswd-file /etc/rest-server/htpasswd-cust-$1 --private-repos $3
Restart=on-failure
NoNewPrivileges=true
ProtectSystem=strict
ReadWritePaths=/srv/restic-cust
ProtectHome=true
PrivateTmp=true
PrivateDevices=true
ProtectKernelTunables=true
ProtectControlGroups=true
CapabilityBoundingSet=
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
[Install]
WantedBy=multi-user.target
UNIT
}
unit backup 8010 --append-only | put /etc/systemd/system/rest-server-cust-backup.service 0644
unit maint 8011 "" | put /etc/systemd/system/rest-server-cust-maint.service 0644
in_m "systemctl daemon-reload && systemctl enable -q rest-server-cust-backup rest-server-cust-maint && systemctl restart rest-server-cust-backup rest-server-cust-maint; sleep 1; systemctl is-active rest-server-cust-backup rest-server-cust-maint"
echo "per-customer rest-server listeners on $M: :8010 append-only, :8011 maintenance; profiles: $*"
